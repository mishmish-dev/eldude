"""Path-only dependency graphs, deterministic locks, and direct import scopes."""
from dataclasses import dataclass
import json
import os
from pathlib import Path
import tempfile
import tomllib

from eldude.project_model import read_manifest, check_compatibility, satisfies, source_files
from eldude.source_modules import STDLIB, HOST_MODULE, _header
from eldude.source_syntax import Diagnostic


@dataclass
class ProjectGraph:
    selection: object
    packages: dict
    edges: list
    unresolved: list


def resolve(selection, *, inspect=False):
    packages, edges, unresolved, active = {}, [], [], []
    members = {m.name for m in selection.members}

    def visit(package, chain):
        name = package.name
        if name in active:
            package.fail('dependencies', 'package dependency cycle: ' + ' -> '.join(active + [name]))
        if name in packages:
            previous, previous_chain = packages[name]
            if previous.path != package.path:
                package.fail('package.name', f'conflicting origins for {name}: {previous.path} ({previous_chain}) '
                             f'and {package.path} ({chain})')
            return
        if not inspect:
            check_compatibility(package)
        packages[name] = (package, chain)
        active.append(name)
        kinds = ('dependencies', 'dev-dependencies') if name in members else ('dependencies',)
        for kind in kinds:
            for dependency, requirement in sorted(package.data.get(kind, {}).items()):
                field = kind + '.' + dependency
                edge = {'from': name, 'to': dependency, 'kind': kind, 'requirement': requirement}
                edges.append(edge)
                reason = None
                if 'path' not in requirement:
                    reason = 'Implementation limit: only path dependencies are supported'
                    if not inspect:
                        package.fail(field, reason, 'unsupported')
                else:
                    path = package.path.parent / requirement['path'] / 'eldude.toml'
                    if not path.is_file():
                        reason = f'missing path dependency manifest: {path}'
                        if not inspect:
                            package.fail(field, reason)
                    else:
                        target = read_manifest(path)
                        if target.name != dependency:
                            package.fail(field, f'dependency name must match declared package name {target.name!r}')
                        if 'version' in requirement and not satisfies(target.data['package']['version'], requirement['version']):
                            package.fail(field, f'{chain} -> {dependency}: package version does not satisfy {requirement["version"]}')
                        visit(target, chain + ' -> ' + dependency)
                if reason:
                    unresolved.append(edge | {'reason': reason})
        active.pop()

    for member in selection.members:
        visit(member, member.name)
    return ProjectGraph(selection, {name: value[0] for name, value in sorted(packages.items())},
                        sorted(edges, key=lambda e: (e['from'], e['kind'], e['to'])), unresolved)


def lock_data(graph):
    root = graph.selection.root
    packages = []
    for name, package in graph.packages.items():
        packages.append({'name': name, 'version': package.data['package']['version'],
                         'path': Path(os.path.relpath(package.path.parent, root)).as_posix()})
    return {'lock-version': 1, 'resolver-version': 1, 'package': packages, 'edge': graph.edges}


def render_lock(data):
    quote = lambda value: json.dumps(value, ensure_ascii=False)
    lines = ['# Generated by eldude; commit this file.', 'lock-version = 1', 'resolver-version = 1']
    # Empty arrays must precede tables to remain top-level TOML keys.
    for key in ('package', 'edge'):
        if not data[key]:
            lines.append(key + ' = []')
    for package in data['package']:
        lines.extend(['', '[[package]]', *(f'{key} = {quote(value)}' for key, value in package.items())])
    for edge in data['edge']:
        lines.extend(['', '[[edge]]', *(f'{key} = {quote(edge[key])}' for key in ('from', 'to', 'kind'))])
        requirement = ', '.join(f'{key} = {quote(value)}' for key, value in sorted(edge['requirement'].items()))
        lines.append('requirement = { ' + requirement + ' }')
    return '\n'.join(lines) + '\n'


def atomic_write(path, content):
    path = Path(path)
    if path.is_symlink():
        raise ValueError(f'{path}: refusing to replace a symlink')
    temporary = None
    try:
        with tempfile.NamedTemporaryFile(dir=path.parent, prefix='.' + path.name + '.', delete=False) as stream:
            temporary = Path(stream.name)
            stream.write(content)
            stream.flush()
            os.fsync(stream.fileno())
        os.replace(temporary, path)
    finally:
        if temporary is not None:
            temporary.unlink(missing_ok=True)


def reconcile_lock(graph, *, locked=False):
    path = graph.selection.root / 'eldude.lock'
    wanted = lock_data(graph)
    previous = None
    if path.exists():
        try:
            previous = tomllib.loads(path.read_text(encoding='utf-8'))
        except tomllib.TOMLDecodeError as error:
            graph.selection.owner.fail('eldude.lock', f'invalid lockfile: {error}')
    if previous == wanted:
        return False
    if locked:
        graph.selection.owner.fail('eldude.lock', 'missing or stale lockfile; run eldude lock without --locked')
    for package in graph.packages.values():
        if package.path.read_text(encoding='utf-8') != package.text:
            package.fail('dependencies', 'manifest changed during resolution; retry')
    atomic_write(path, render_lock(wanted).encode('utf-8'))
    return True


def module_sources(graph, selected, *, tests=False):
    """Index the selected closure; each importing module keeps its owner's scope."""
    selected = {p.name for p in selected}
    included = set()

    def include(name):
        if name in included:
            return
        included.add(name)
        for edge in graph.edges:
            if edge['from'] == name and (edge['kind'] == 'dependencies' or tests and name in selected):
                include(edge['to'])

    for name in selected:
        include(name)
    paths, owners, declarations = [], {}, {}
    for name in sorted(included):
        package = graph.packages[name]
        for path in source_files(package, tests=tests and name in selected):
            paths.append(path)
            header = _header(path.read_text(encoding='utf-8'), path)
            if header:
                identity, span = header
                if identity == HOST_MODULE or identity in declarations:
                    related = [('Other provider', declarations[identity])] if identity in declarations else ()
                    raise Diagnostic('module', f'Duplicate or reserved module identity {identity!r}', span, related)
                declarations[identity] = span
                owners[identity] = (name, path.is_relative_to(package.directory('test-dir')))
    bundled = set()
    for path in sorted(STDLIB.rglob('*.eld')):
        header = _header(path.read_text(encoding='utf-8'), path)
        if header:
            identity, span = header
            bundled.add(identity)
            if identity in declarations:
                raise Diagnostic('module', f'Duplicate module identity {identity!r}', declarations[identity],
                                 [('Bundled provider', span)])

    def allowed(importer, imported):
        if imported == HOST_MODULE or imported in bundled:
            return True
        if importer not in owners or imported not in owners:
            return False
        owner, test_source = owners[importer]
        provider, test_provider = owners[imported]
        if test_provider:
            return test_source and owner == provider
        if owner == provider:
            return True
        return any(e['from'] == owner and e['to'] == provider and
                   (e['kind'] == 'dependencies' or test_source) for e in graph.edges)

    return sorted(paths), allowed
